export function categorizeIconName(name: string): IconCategory {
  if (ARROW_ICONS.has(name)) return "Arrows & Direction"
  if (FILE_ICONS.has(name)) return "Files & Folders"
  if (COMMUNICATION_ICONS.has(name)) return "Communication & Social"
  if (MEDIA_DEVICE_ICONS.has(name)) return "Media & Devices"
  if (COMMERCE_ICONS.has(name)) return "Commerce & Finance"
  if (WEATHER_NATURE_ICONS.has(name)) return "Weather & Nature"
  if (FOOD_DRINK_ICONS.has(name)) return "Food & Drink"
  if (SHAPE_SPARKLE_ICONS.has(name)) return "Shapes & Sparkles"
  if (OBJECT_MISC_ICONS.has(name)) return "Objects & Misc"
  return "Interface & Layout"
}

export function getIconTags(name: string, category: IconCategory): string[] {
  const words = name.split("-").filter((part) => !/^\d+$/.test(part))
  const categoryWords = category
    .toLowerCase()
    .split(/[\s&]+/)
    .filter(Boolean)
  const aliases = TAG_ALIASES[name] ?? []

  return Array.from(new Set([...words, ...aliases, ...categoryWords, "glass"]))
}

function formatIconTitle(name: string): string {
  const acronyms = new Set(["ssd", "ufo", "vr"])
  return name
    .split("-")
    .map((part) =>
      acronyms.has(part)
        ? part.toUpperCase()
        : part.charAt(0).toUpperCase() + part.slice(1)
    )
    .join(" ")
}

function formatComponentName(name: string): string {
  const pascal = name
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("")
  return `${pascal}Icon`
}

export const NUCLEO_ICONS: IconItem[] = NUCLEO_ICON_NAMES.map((name) => {
  const category = categorizeIconName(name)
  return {
    name,
    title: formatIconTitle(name),
    componentName: formatComponentName(name),
    library: "nucleo",
    category,
    tags: getIconTags(name, category),
    src: `/icons/nucleo/${name}.svg`,
    viewBox: VIEWBOX_OVERRIDES[name] ?? "0 0 24 24",
  }
})

export function getIcons(library?: IconLibraryId): IconItem[] {
  if (!library || library === "nucleo") {
    return NUCLEO_ICONS
  }
  return []
}
